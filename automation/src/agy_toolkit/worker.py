@dataclass
class StepExecutionResult:
    """Outcome payload generated by worker upon processing a pipeline step."""
    step_name: str
    run_id: str
    status: str  # COMPLETED or FAILED
    result: Optional[Any] = None
    error: Optional[str] = None
    exit_code: int = 0
    duration_ms: int = 0
    claimer: Optional[str] = None
    event_id: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Serialize result to dictionary."""
        return asdict(self)


class HeartbeatSupervisor:
    """Background supervisor daemon maintaining claim lease renewal during step execution."""

    def __init__(
        self,
        event_id: str,
        claimer: str,
        interval_seconds: float = 10.0,
        extend_seconds: int = 60,
        memory_dir: Optional[Path] = None,
    ):
        self.event_id = event_id
        self.claimer = claimer
        self.interval_seconds = interval_seconds
        self.extend_seconds = extend_seconds
        self.memory_dir = memory_dir
        self._stop_event = threading.Event()
        self._thread: Optional[threading.Thread] = None

    def start(self) -> None:
        """Start the background heartbeat renewal loop."""
        self._stop_event.clear()
        self._thread = threading.Thread(target=self._run, daemon=True)
        self._thread.start()

    def _run(self) -> None:
        """Periodically ping heartbeat until stopped."""
        while not self._stop_event.wait(self.interval_seconds):
            success = heartbeat_claim(
                event_id=self.event_id,
                claimer=self.claimer,
                extend_seconds=self.extend_seconds,
                memory_dir=self.memory_dir,
            )
            if not success:
                break

    def stop(self) -> None:
        """Signal and wait for the heartbeat supervisor thread to terminate."""
        self._stop_event.set()
        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=2.0)


def execute_step_task(
    payload: Dict[str, Any],
    timeout_seconds: int = 300,
    workspace_root: Optional[Path] = None,
    command_override: Optional[str] = None,
) -> StepExecutionResult:
    """Execute the workload associated with a dispatched step."""
    start_time = time.perf_counter()
    run_id = str(payload.get("run_id", "unknown_run"))
    step_name = str(payload.get("step", "unknown_step"))
    role = str(payload.get("role", "general"))
    context = payload.get("context", {}) if isinstance(payload.get("context"), dict) else {}
    upstream_results = payload.get("upstream_results", {})

    # Check for command execution directive
    command_to_run = command_override
    if not command_to_run:
        step_commands = context.get("step_commands", {})
        if isinstance(step_commands, dict) and step_name in step_commands:
            command_to_run = step_commands[step_name]
        elif context.get("command"):
            command_to_run = str(context["command"])

    # 1. Shell command execution mode
    if command_to_run:
        cwd = str(workspace_root) if workspace_root else None
        try:
            proc = subprocess.run(
                command_to_run,
                shell=True,
                capture_output=True,
                text=True,
                timeout=timeout_seconds,
                cwd=cwd,
            )
            duration_ms = int((time.perf_counter() - start_time) * 1000)
            if proc.returncode == 0:
                return StepExecutionResult(
                    step_name=step_name,
                    run_id=run_id,
                    status="COMPLETED",
                    result={
                        "stdout": proc.stdout.strip(),
                        "exit_code": 0,
                        "command": command_to_run,
                    },
                    exit_code=0,
                    duration_ms=duration_ms,
                )
            else:
                err_detail = proc.stderr.strip() or proc.stdout.strip() or f"Process exited with {proc.returncode}"
                return StepExecutionResult(
                    step_name=step_name,
                    run_id=run_id,
                    status="FAILED",
                    error=f"Command execution failed: {err_detail}",
                    exit_code=proc.returncode,
                    duration_ms=duration_ms,
                )
        except subprocess.TimeoutExpired:
            duration_ms = int((time.perf_counter() - start_time) * 1000)
            return StepExecutionResult(
                step_name=step_name,
                run_id=run_id,
                status="FAILED",
                error=f"Step execution timed out after {timeout_seconds} seconds.",
                exit_code=124,
                duration_ms=duration_ms,
            )
        except Exception as ex:
            duration_ms = int((time.perf_counter() - start_time) * 1000)
            return StepExecutionResult(
                step_name=step_name,
                run_id=run_id,
                status="FAILED",
                error=f"Execution error: {str(ex)}",
                exit_code=1,
                duration_ms=duration_ms,
            )

    # 2. Specialist subagent simulation / acknowledgement mode
    duration_ms = int((time.perf_counter() - start_time) * 1000)
    result_data = {
        "role": role,
        "step": step_name,
        "processed": True,
        "upstream_results": upstream_results,
        "summary": f"Step '{step_name}' successfully processed by role '{role}'.",
    }
    return StepExecutionResult(
        step_name=step_name,
        run_id=run_id,
        status="COMPLETED",
        result=result_data,
        exit_code=0,
        duration_ms=duration_ms,
    )


class SwarmWorker:
    """Autonomous worker daemon claiming dispatched steps and advancing DAG workflows."""

    def __init__(
        self,
        worker_id: Optional[str] = None,
        memory_dir: Optional[Path] = None,
        workspace_root: Optional[Path] = None,
        poll_interval: float = 0.5,
        lease_seconds: int = 60,
        timeout_seconds: int = 300,
    ):
        self.worker_id = worker_id or f"worker_{uuid.uuid4().hex[:8]}"
        self.workspace_root = Path(workspace_root).resolve() if workspace_root else Path.cwd()
        self.mem_dir = Path(memory_dir).resolve() if memory_dir else self.workspace_root / ".agents" / "memory"
        self.poll_interval = max(0.1, poll_interval)
        self.lease_seconds = max(10, lease_seconds)
        self.timeout_seconds = max(1, timeout_seconds)
        self.last_result: Optional[StepExecutionResult] = None
        self.processed_count = 0

    def get_ready_step_events(self) -> List[BusEvent]:
        """Scan volatile bus for active events belonging to DAG pipeline steps."""
        all_events = list_events(memory_dir=self.mem_dir)
        step_events: List[BusEvent] = []
        for e in all_events:
            payload = e.payload
            if isinstance(payload, dict) and "run_id" in payload and "step" in payload:
                step_events.append(e)
        return step_events

    def run_once(self, command_override: Optional[str] = None) -> Optional[StepExecutionResult]:
        """Perform a single atomic claim, execution, and advance sweep."""
        candidates = self.get_ready_step_events()
        if not candidates:
            return None

        for event in candidates:
            # Attempt atomic claim
            claimed_event = claim_event(
                event_id=event.id,
                claimer=self.worker_id,
                lease_seconds=self.lease_seconds,
                memory_dir=self.mem_dir,
            )
            if not claimed_event:
                continue

            payload = claimed_event.payload if isinstance(claimed_event.payload, dict) else {}
            run_id = str(payload.get("run_id", ""))
            step_name = str(payload.get("step", ""))

            # Mark step as CLAIMED in pipeline state
            try:
                advance_step(
                    run_id=run_id,
                    step_name=step_name,
                    status="CLAIMED",
                    claimer=self.worker_id,
                    memory_dir=self.mem_dir,
                )
            except ValueError:
                pass

            # Start supervisor heartbeat during task execution
            supervisor = HeartbeatSupervisor(
                event_id=event.id,
                claimer=self.worker_id,
                interval_seconds=max(2.0, self.lease_seconds / 3.0),
                extend_seconds=self.lease_seconds,
                memory_dir=self.mem_dir,
            )
            supervisor.start()

            try:
                result = execute_step_task(
                    payload=payload,
                    timeout_seconds=self.timeout_seconds,
                    workspace_root=self.workspace_root,
                    command_override=command_override,
                )
            finally:
                supervisor.stop()

            result.claimer = self.worker_id
            result.event_id = event.id

            # Advance pipeline run state with result
            try:
                advance_step(
                    run_id=run_id,
                    step_name=step_name,
                    status=result.status,
                    result=result.result,
                    error=result.error,
                    claimer=self.worker_id,
                    memory_dir=self.mem_dir,
                )
            except ValueError:
                pass

            # Complete event on volatile bus
            complete_claimed_event(
                event_id=event.id,
                claimer=self.worker_id,
                memory_dir=self.mem_dir,
            )

            self.last_result = result
            self.processed_count += 1
            return result

        return None

    def run_loop(
        self,
        stop_event: Optional[threading.Event] = None,
        max_cycles: Optional[int] = None,
    ) -> List[StepExecutionResult]:
        """Execute continuous worker polling loop until stopped or max_cycles met."""
        results: List[StepExecutionResult] = []
        cycles = 0

        while True:
            if stop_event and stop_event.is_set():
                break
            if max_cycles is not None and cycles >= max_cycles:
                break

            cycles += 1
            res = self.run_once()
            if res is not None:
                results.append(res)
            else:
                if stop_event:
                    if stop_event.wait(self.poll_interval):
                        break
                else:
                    time.sleep(self.poll_interval)

        return results

def handle_swarm_mcp_tool(
    name: str, arguments: Dict[str, Any], mem_dir: Path
) -> Optional[Tuple[str, bool]]:
    """Dispatch swarm-related MCP tool calls. Returns (result_text, is_error) or None if unhandled."""
    if name == "agy_swarm_run":
        pipeline_name = arguments.get("pipeline")
        if not pipeline_name:
            return "Error: Missing required argument 'pipeline'.", True
        stack = arguments.get("stack")
        context = dict(arguments.get("context") or {})
        if stack:
            context["stack"] = stack

        try:
            run = create_pipeline_run(
                pipeline_name=pipeline_name,
                context=context,
                memory_dir=mem_dir,
            )
            return json.dumps(run.to_dict(), indent=2), False
        except ValueError as ex:
            return f"Error: {str(ex)}", True

    if name == "agy_swarm_status":
        run_id = arguments.get("run_id")
        if not run_id:
            return "Error: Missing required argument 'run_id'.", True
        run = load_pipeline_run(run_id, memory_dir=mem_dir)
        if not run:
            return f"Error: Pipeline run '{run_id}' not found.", True
        return json.dumps(run.to_dict(), indent=2), False

    if name == "agy_swarm_advance":
        run_id = arguments.get("run_id")
        step_name = arguments.get("step")
        status = arguments.get("status")
        if not run_id or not step_name or not status:
            return "Error: 'run_id', 'step', and 'status' are required.", True

        result = arguments.get("result")
        error = arguments.get("error")
        claimer = arguments.get("claimer")

        try:
            run = advance_step(
                run_id=run_id,
                step_name=step_name,
                status=status.upper(),
                result=result,
                error=error,
                claimer=claimer,
                memory_dir=mem_dir,
            )
            return json.dumps(run.to_dict(), indent=2), False
        except ValueError as ex:
            return f"Error: {str(ex)}", True

    if name == "agy_swarm_cancel":
        run_id = arguments.get("run_id")
        if not run_id:
            return "Error: Missing required argument 'run_id'.", True
        reason = arguments.get("reason", "Operator cancelled via MCP")
        run = cancel_pipeline_run(run_id, reason=reason, memory_dir=mem_dir)
        if not run:
            return f"Error: Pipeline run '{run_id}' not found.", True
        return f"Pipeline run '{run_id}' cancelled. Reason: {reason}", False

    if name == "agy_swarm_worker_cycle":
        from agy_toolkit.worker import SwarmWorker

        timeout_sec = int(arguments.get("timeout_seconds", 300) or 300)
        cmd_override = arguments.get("command_override")
        worker = SwarmWorker(
            memory_dir=mem_dir,
            timeout_seconds=timeout_sec,
        )
        res = worker.run_once(command_override=cmd_override)
        if res is None:
            return json.dumps({
                "processed": False,
                "message": "No claimable dispatched steps found on volatile bus.",
            }, indent=2), False
        return json.dumps({
            "processed": True,
            "step": res.step_name,
            "run_id": res.run_id,
            "status": res.status,
            "result": res.result,
            "error": res.error,
            "duration_ms": res.duration_ms,
        }, indent=2), res.status == "FAILED"

    if name == "agy_swarm_worker_status":
        from agy_toolkit.worker import SwarmWorker

        worker = SwarmWorker(memory_dir=mem_dir)
        ready_events = worker.get_ready_step_events()
        items = []
        for e in ready_events:
            p = e.payload if isinstance(e.payload, dict) else {}
            items.append({
                "event_id": e.id,
                "run_id": p.get("run_id"),
                "step": p.get("step"),
                "role": p.get("role"),
            })
        return json.dumps({
            "worker_ready": True,
            "ready_steps_count": len(items),
            "ready_steps": items,
        }, indent=2), False

    return None
